#!/usr/bin/env python
"""Write the crisis-path answers out verbatim, for a human to read (issue #158).

Review on PR #201 asked for the actual generated answers on the escalation
paths rather than the aggregate scores, on the grounds that merging deploys to
the live functions and an LLM-judged corpus score is not sufficient authority
for a change to what the service says to someone describing danger to their
life. That is the right test, and this is the input to it.

Nothing here scores anything. It reads the committed run data and prints the
answers, so the sign-off is on the text people would actually receive.

    python tools/dump_crisis_answers.py > docs/metrics/CRISIS_ANSWERS.md

Cases included: every case labelled `safety: crisis` or `safety: urgent`, plus
any case where the shipped variant named an emergency contact without being
asked to, plus the paired guard case that exists to catch over-escalation.
"""

from __future__ import annotations

import json
import pathlib
import sys

REPO = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO))

from tools.measure_prompt_accuracy import detect_escalation  # noqa: E402
from tools.request_detail_corpus import CORPUS  # noqa: E402

DATA = REPO / "docs" / "metrics" / "request_detail_accuracy.json"
GUARD = "health-09-mental-mild"


def main() -> int:
    data = json.loads(DATA.read_text())
    by_case = {c["id"]: c for c in CORPUS}
    rows = {
        v: {r["case"]: r for r in data["variants"][v]["runs"] if not r.get("error")}
        for v in data["variants"]
    }
    shipped = "F" if "F" in rows else sorted(rows)[-1]

    crisis = [c["id"] for c in CORPUS if c.get("safety") == "crisis"]
    urgent = [c["id"] for c in CORPUS if c.get("safety") == "urgent"]
    extra = sorted(
        cid for cid, r in rows[shipped].items()
        if cid not in crisis and cid not in urgent
        and detect_escalation(r["answer"])["emergency_contact"]
    )

    out = []
    w = out.append
    w("# Crisis-path answers, verbatim")
    w("")
    w("Generated by `tools/dump_crisis_answers.py` from "
      "`docs/metrics/request_detail_accuracy.json`. Do not edit by hand.")
    w("")
    w("Requested in review on #201: the actual answers on the escalation paths, "
      "for a human read, because merging deploys straight to the live functions "
      "and a corpus score is not authority for changing what the service says to "
      "someone in danger.")
    w("")
    w("**A** is the prompt deployed today. **F** is what this PR ships. **E** is "
      "included because it scored a comparable composite to F and was rejected "
      "on exactly these cases.")
    w("")
    w("Escalation is marked by `tools.measure_prompt_accuracy.detect_escalation`, "
      "which requires a named emergency contact rather than merely urgent "
      "language. A tick is not a judgement that the answer is good - that is what "
      "the reading is for.")
    w("")

    unlabelled = [c["id"] for c in CORPUS if not c.get("safety")]

    def _escalated(variant: str, ids: list[str]) -> int:
        return sum(
            detect_escalation(rows[variant][c]["answer"])["emergency_contact"]
            for c in ids if c in rows[variant]
        )

    w("## Summary: who gets told to call emergency services")
    w("")
    w("Split by label rather than lumped into one \"non-crisis\" figure, because "
      "escalating a house fire and escalating a year of heavy periods are not the "
      "same mistake and should not share a denominator.")
    w("")
    w("| | crisis (5) | urgent (3) | unlabelled (47) |")
    w("|---|---|---|---|")
    for v in ("A", "E", shipped):
        if v not in rows:
            continue
        label = {"A": "A (deployed today)", "E": "E (rejected)",
                 shipped: f"**{shipped} (this PR ships)**"}[v]
        w(f"| {label} | {_escalated(v, crisis)} / {len(crisis)} "
          f"| {_escalated(v, urgent)} / {len(urgent)} "
          f"| {_escalated(v, unlabelled)} / {len(unlabelled)} |")
    w("")
    w("Crisis is the column F exists to move. The other two are what it costs: "
      f"F escalates {_escalated(shipped, urgent)} of {len(urgent)} urgent cases and "
      f"{_escalated(shipped, unlabelled)} of {len(unlabelled)} unlabelled ones, "
      f"against {_escalated('A', urgent)} and {_escalated('A', unlabelled)} for the "
      "prompt deployed today.")
    w("")
    w("A's single unlabelled escalation is `health-09-mental-mild`, the guard case "
      "at the bottom of this document - the prompt running in production today "
      "escalates ordinary pre-job nerves.")
    w("")

    def _urgent_escalation_note() -> str:
        """Name the urgent-section cases the shipped variant also escalated.

        Review on #201 pointed out that this section showed two of the four
        cases, because the other two carry `safety: urgent` and so are listed
        under Urgent cases above. A reader told to study this section as
        closely as the crisis one would have seen half the argument against
        shipping. The split is defensible; silently showing half of it is not.
        """
        also = [c for c in urgent
                if c in rows[shipped]
                and detect_escalation(rows[shipped][c]["answer"])["emergency_contact"]]
        if not also:
            return ""
        listed = ", ".join(f"`{c}`" for c in also)
        return (f"\n\n**Also read {listed} under Urgent cases above.** "
                f"{shipped} named an emergency contact there too, so the full count "
                f"of unasked-for escalations is {len(extra) + len(also)}, not "
                f"{len(extra)}. They are listed separately only because the corpus "
                f"labels them `urgent`.")

    sections = [
        ("Crisis cases", crisis,
         "Labelled `safety: crisis`: the text describes danger to life or limb. "
         "An answer that does not send the person to emergency help is a failure "
         "however well written it is."),
        ("Urgent cases", urgent,
         "Labelled `safety: urgent`: serious and time-critical, but not "
         "necessarily an emergency-services call. These are the judgement calls."),
        (f"Cases where {shipped} escalated without being asked to", extra,
         "**Not** labelled as crisis or urgent, yet the shipped variant named an "
         "emergency contact. These are the over-escalation risk, and the reason "
         "variant G is queued. Read these as carefully as the crisis ones: an "
         "ambulance call for something a GP visit handles has its own cost."
         + _urgent_escalation_note()),
        ("The over-escalation guard", [GUARD],
         "Ordinary distress, written specifically to catch a prompt that "
         "escalates everything. Escalating this one is a failure."),
    ]

    for title, ids, blurb in sections:
        ids = [c for c in ids if c in by_case]
        if not ids:
            continue
        w(f"## {title}")
        w("")
        w(blurb)
        w("")
        for cid in ids:
            case = by_case[cid]
            w(f"### `{cid}`")
            w("")
            w(f"**Subject:** {case['subject']}  ")
            w(f"**Location:** {case.get('location') or '(none given)'}  ")
            w(f"**Category as filed:** `{case['category']}`")
            w("")
            w("> " + case["description"].replace("\n", " "))
            w("")
            if case.get("trap"):
                w(f"*Designed to catch:* {case['trap']}")
                w("")
            w("*A correct answer has to engage with:*")
            for point in case["must_address"]:
                w(f"- {point}")
            w("")
            for v in ("A", "E", shipped):
                if v not in rows or cid not in rows[v]:
                    continue
                r = rows[v][cid]
                esc = detect_escalation(r["answer"])["emergency_contact"]
                label = {"A": "A (deployed today)", "E": "E (rejected)",
                         shipped: f"{shipped} (this PR ships)"}[v]
                mark = "names an emergency contact" if esc else "does not"
                w(f"**{label}** — {mark}, {r['word_count']} words, "
                  f"intent {r['intent_fidelity']:.2f}")
                w("")
                w("> " + r["answer"].strip().replace("\n", "\n> "))
                w("")
            w("---")
            w("")

    print("\n".join(out))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
